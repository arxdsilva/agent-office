/** A user-safe message from any thrown value (never a stack or path). */
export function errorText(e: unknown): string {
  const m = e instanceof Error ? e.message : typeof e === 'string' ? e : ''
  return m.trim().slice(0, 200) || WS_COPY.errors.generic
}
